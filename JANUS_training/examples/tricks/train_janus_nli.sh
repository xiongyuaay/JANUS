export PREDICT_TEXT_REWARD_IN_VAL=${PREDICT_TEXT_REWARD_IN_VAL:-${predict_text_reward_in_val:-false}}
export predict_text_reward_in_val="${PREDICT_TEXT_REWARD_IN_VAL}"

