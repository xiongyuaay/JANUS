export predict_bleu_max_order="${PREDICT_BLEU_MAX_ORDER}"
export PREDICT_BLEU_SMOOTH=${PREDICT_BLEU_SMOOTH:-${predict_bleu_smooth:-true}}
export predict_bleu_smooth="${PREDICT_BLEU_SMOOTH}"

# Local NLI backend (fully offline if the model snapshot is already on disk).
export PREDICT_NLI_MODEL_PATH=${PREDICT_NLI_MODEL_PATH:-${predict_nli_model_path:-}}
export predict_nli_model_path="${PREDICT_NLI_MODEL_PATH}"
export PREDICT_NLI_TOKENIZER_PATH=${PREDICT_NLI_TOKENIZER_PATH:-${predict_nli_tokenizer_path:-${PREDICT_NLI_MODEL_PATH}}}
export predict_nli_tokenizer_path="${PREDICT_NLI_TOKENIZER_PATH}"
# Note: PREDICT_NLI_DEVICE / PREDICT_NLI_BATCH_SIZE defaults are decided by the
# reward-actor placement block below (auto-picks cuda or cpu based on
# REWARD_GPU_SHARE_DEVICE / REWARD_NUM_GPUS). Only mirror user-provided values
# between upper/lower case here.
PREDICT_NLI_DEVICE=${PREDICT_NLI_DEVICE:-${predict_nli_device:-}}
PREDICT_NLI_BATCH_SIZE=${PREDICT_NLI_BATCH_SIZE:-${predict_nli_batch_size:-}}
PREDICT_NLI_CPU_THREADS=${PREDICT_NLI_CPU_THREADS:-${predict_nli_cpu_threads:-}}
export PREDICT_NLI_MAX_LENGTH=${PREDICT_NLI_MAX_LENGTH:-${predict_nli_max_length:-512}}
export predict_nli_max_length="${PREDICT_NLI_MAX_LENGTH}"
export PREDICT_NLI_BIDIRECTIONAL=${PREDICT_NLI_BIDIRECTIONAL:-${predict_nli_bidirectional:-true}}
export predict_nli_bidirectional="${PREDICT_NLI_BIDIRECTIONAL}"
export PREDICT_NLI_EMPTY_SCORE=${PREDICT_NLI_EMPTY_SCORE:-${predict_nli_empty_score:-0.0}}
export predict_nli_empty_score="${PREDICT_NLI_EMPTY_SCORE}"
export PREDICT_NLI_LABEL_MAP=${PREDICT_NLI_LABEL_MAP:-${predict_nli_label_map:-}}
export predict_nli_label_map="${PREDICT_NLI_LABEL_MAP}"
export PREDICT_NLI_LOCAL_FILES_ONLY=${PREDICT_NLI_LOCAL_FILES_ONLY:-${predict_nli_local_files_only:-true}}
export predict_nli_local_files_only="${PREDICT_NLI_LOCAL_FILES_ONLY}"
export PREDICT_NLI_TRUST_REMOTE_CODE=${PREDICT_NLI_TRUST_REMOTE_CODE:-${predict_nli_trust_remote_code:-false}}
export predict_nli_trust_remote_code="${PREDICT_NLI_TRUST_REMOTE_CODE}"

# -----------------------------
# vLLM embedding service (required when PREDICT_SIMILARITY=true).
# function.py reads either upper- or lower-case, export both for safety.
# -----------------------------
export VLLM_EMBEDDING_BASE_URL=${VLLM_EMBEDDING_BASE_URL:-http://10.102.234.19:10034/v1}
export VLLM_EMBEDDING_MODEL=${VLLM_EMBEDDING_MODEL:-Qwen/Qwen3-Embedding-4B}
export VLLM_EMBEDDING_API_KEY=${VLLM_EMBEDDING_API_KEY:-EMPTY}
export VLLM_EMBEDDING_MAX_CONCURRENCY=${VLLM_EMBEDDING_MAX_CONCURRENCY:-256}
export VLLM_EMBEDDING_BATCH_SIZE=${VLLM_EMBEDDING_BATCH_SIZE:-32}
export VLLM_EMBEDDING_TIMEOUT_S=${VLLM_EMBEDDING_TIMEOUT_S:-180}
export VLLM_EMBEDDING_MAX_RETRIES=${VLLM_EMBEDDING_MAX_RETRIES:-3}
export vllm_embedding_base_url=${vllm_embedding_base_url:-${VLLM_EMBEDDING_BASE_URL}}
export vllm_embedding_model=${vllm_embedding_model:-${VLLM_EMBEDDING_MODEL}}
export vllm_embedding_api_key=${vllm_embedding_api_key:-${VLLM_EMBEDDING_API_KEY}}
export vllm_embedding_max_concurrency=${vllm_embedding_max_concurrency:-${VLLM_EMBEDDING_MAX_CONCURRENCY}}
export vllm_embedding_batch_size=${vllm_embedding_batch_size:-${VLLM_EMBEDDING_BATCH_SIZE}}
export vllm_embedding_timeout_s=${vllm_embedding_timeout_s:-${VLLM_EMBEDDING_TIMEOUT_S}}
export vllm_embedding_max_retries=${vllm_embedding_max_retries:-${VLLM_EMBEDDING_MAX_RETRIES}}

# Disable the legacy caption gate (vLLM judge) and discard mode.
export vllm_judge=${vllm_judge:-false}
export discard=${discard:-false}

# -----------------------------
# Reward actor placement (auto-adapts to 4 / 8 / 32 H200 jobs).
#
# Default: local NLI reward workers share the visible actor GPUs via Ray
# runtime_env CUDA_VISIBLE_DEVICES overrides. There is still zero logical GPU
# reservation, so the actor pool keeps all NUM_GPUS and the FSDP batch
# divisibility constraints in fsdp_workers.py remain unchanged. main.py creates
# one reward worker per listed share device when REWARD_NUM_ACTORS is not set,
# so a 32-GPU job computes NLI rewards in parallel across 32 co-resident
# workers. H200's 141 GB has ample headroom for deberta-v3-base (~700 MB)
# alongside the FSDP shard.
#
# Override knobs:
#   REWARD_GPU_SHARE_DEVICE=""    -> disable sharing; if REWARD_NUM_GPUS=0
#                                    and no share device, NLI auto-falls back
#                                    to CPU (because Ray sets
#                                    CUDA_VISIBLE_DEVICES="" for num_gpus=0
#                                    actors, and predict_text_reward.py's
#                                    _resolve_device degrades cuda->cpu when
#                                    torch.cuda.is_available() is False).
#   REWARD_GPU_SHARE_DEVICE=0,1   -> share two devices; reward workers are
#                                    placed round-robin on this list.
#   REWARD_NUM_ACTORS=8           -> use only 8 parallel reward workers even
#                                    when more share devices are listed.
#   REWARD_NUM_GPUS=0.5           -> reserve fractional logical GPUs per
#                                    reward actor instead of sharing. You
#                                    MUST then lower N_GPUS_PER_NODE and
#                                    re-pick ACTOR_GLOBAL_BATCH_SIZE /
#                                    ROLLOUT_BATCH_SIZE so batch math survives
#                                    the smaller actor world.
# -----------------------------
REWARD_NUM_GPUS=${REWARD_NUM_GPUS:-0}
REWARD_NUM_CPUS=${REWARD_NUM_CPUS:-1}
if [ -z "${REWARD_CPU_FALLBACK_ACTORS+x}" ]; then
  REWARD_CPU_FALLBACK_ACTORS=$(awk -v cores="${CPU_CORES}" -v per="${REWARD_NUM_CPUS}" 'BEGIN{if (per<=0) per=1; n=int(cores/per); if (n<1) n=1; if (n>8) n=8; print n}')
fi
export REWARD_CPU_FALLBACK_ACTORS
# Default share-device = all detected GPUs. An explicitly-set empty string
# disables sharing and makes NLI use parallel CPU reward actors.
if [ -z "${REWARD_GPU_SHARE_DEVICE+x}" ]; then
  REWARD_GPU_SHARE_DEVICE=""
  if [ "${NUM_GPUS}" -gt 0 ]; then
    for ((gpu_i = 0; gpu_i < NUM_GPUS; gpu_i++)); do
      if [ -z "${REWARD_GPU_SHARE_DEVICE}" ]; then
        REWARD_GPU_SHARE_DEVICE="${gpu_i}"
      else
        REWARD_GPU_SHARE_DEVICE="${REWARD_GPU_SHARE_DEVICE},${gpu_i}"
      fi
    done
  fi
fi
export REWARD_GPU_SHARE_DEVICE

DEFAULT_REWARD_NUM_ACTORS=1
if [ -n "${REWARD_GPU_SHARE_DEVICE}" ]; then
  IFS=',' read -r -a REWARD_GPU_SHARE_DEVICES <<< "${REWARD_GPU_SHARE_DEVICE}"
  DEFAULT_REWARD_NUM_ACTORS=${#REWARD_GPU_SHARE_DEVICES[@]}
elif [ "${PREDICT_TEXT_REWARD_TYPE}" = "nli" ] \
  && [ "$(awk -v x="${REWARD_NUM_GPUS}" 'BEGIN{print (x>0)?1:0}')" -eq 0 ]; then
  DEFAULT_REWARD_NUM_ACTORS=${REWARD_CPU_FALLBACK_ACTORS}
fi
REWARD_NUM_ACTORS=${REWARD_NUM_ACTORS:-${DEFAULT_REWARD_NUM_ACTORS}}
if ! [[ "${REWARD_NUM_ACTORS}" =~ ^[0-9]+$ ]] || [ "${REWARD_NUM_ACTORS}" -le 0 ]; then
  echo "[ERROR] REWARD_NUM_ACTORS must be a positive integer, got ${REWARD_NUM_ACTORS}." >&2
  exit 1
fi
export REWARD_NUM_ACTORS

if [ -n "${REWARD_GPU_SHARE_DEVICE}" ]; then
  # Shared-GPU mode (default): NLI runs on actor GPU(s) listed in
  # REWARD_GPU_SHARE_DEVICE. No logical GPU reservation; main.py starts
  # REWARD_NUM_ACTORS workers and injects one CUDA_VISIBLE_DEVICES value per
  # worker so torch.cuda sees that worker's assigned device.
  # H200 has 141 GB; deberta-v3-base @ batch=256, max_len=512 fits comfortably
  # alongside the FSDP shard. Larger batch dramatically cuts NLI wall-time
  # during reward eval (the dominant gap between vLLM rollouts).
  PREDICT_NLI_DEVICE=${PREDICT_NLI_DEVICE:-cuda}
  PREDICT_NLI_BATCH_SIZE=${PREDICT_NLI_BATCH_SIZE:-256}
elif [ "$(awk -v x="${REWARD_NUM_GPUS}" 'BEGIN{print (x>0)?1:0}')" -eq 1 ]; then
  # Reserved-GPU mode: caller owns batch-size correctness.
  PREDICT_NLI_DEVICE=${PREDICT_NLI_DEVICE:-cuda}
  PREDICT_NLI_BATCH_SIZE=${PREDICT_NLI_BATCH_SIZE:-256}
else
  # CPU fallback: explicit opt-out via REWARD_GPU_SHARE_DEVICE="", or no
  # detected GPU. Use multiple reward actors and one PyTorch intra-op thread
  # per actor by default to avoid the old single-process CPU bottleneck.
  PREDICT_NLI_DEVICE=${PREDICT_NLI_DEVICE:-cpu}
  PREDICT_NLI_BATCH_SIZE=${PREDICT_NLI_BATCH_SIZE:-16}
  PREDICT_NLI_CPU_THREADS=${PREDICT_NLI_CPU_THREADS:-1}
fi
export PREDICT_NLI_DEVICE
export predict_nli_device="${PREDICT_NLI_DEVICE}"
export PREDICT_NLI_BATCH_SIZE
export predict_nli_batch_size="${PREDICT_NLI_BATCH_SIZE}"
export PREDICT_NLI_CPU_THREADS
export predict_nli_cpu_threads="${PREDICT_NLI_CPU_THREADS}"

N_GPUS_PER_NODE=${N_GPUS_PER_NODE:-${NUM_GPUS}}
if [ "${N_GPUS_PER_NODE}" -le 0 ]; then
  N_GPUS_PER_NODE=1
fi

# -----------------------------
# Length budget for the structured JANUS data
# -----------------------------
MAX_PROMPT_LENGTH=${MAX_PROMPT_LENGTH:-8192}
MAX_RESPONSE_LENGTH=${MAX_RESPONSE_LENGTH:-1536}
PREDICT_MAX_TOKENS=${PREDICT_MAX_TOKENS:-512}
TRAJECTORY_PREFIX_MAX_CHARS=${TRAJECTORY_PREFIX_MAX_CHARS:-6000}
TRUNCATION=${TRUNCATION:-left}

# -----------------------------
# Smoke-test scale knobs
# -----------------------------
EXPERIMENT_NAME=${EXPERIMENT_NAME:-janus_nli_v5.6_test_v2}
MAX_STEPS_VALUE=${MAX_STEPS:-300}
ROLLOUT_BATCH_SIZE_VALUE=${ROLLOUT_BATCH_SIZE:-256}
MINI_ROLLOUT_BATCH_SIZE=${MINI_ROLLOUT_BATCH_SIZE:-${ROLLOUT_BATCH_SIZE_VALUE}}
# val.json currently holds ~1500 samples; with VAL_BATCH_SIZE=32 the validation
# loop becomes ~47 driver-side cycles where each cycle has ~25 s of vLLM
# rollout followed by ~4 min of CPU-bound reward+jinja work, dragging GPU duty
# cycle to <10 %. Keep val_batch close to ROLLOUT_BATCH_SIZE so per-cycle
# overhead is amortized over many prompts.
VAL_BATCH_SIZE_VALUE=${VAL_BATCH_SIZE:-256}
JUDGE_VAL_ROLL_N=${JUDGE_VAL_ROLL_N:-${JUDGE_ROLL_N}}

# -----------------------------
# Logging — output goes to both stdout and a log file by default.
# Override with LOG_DIR=... or LOG_FILE=... if you need a custom location.
# -----------------------------
LOG_DIR=${LOG_DIR:-${ROOT_DIR}/log}
mkdir -p "${LOG_DIR}"
LOG_FILE=${LOG_FILE:-${LOG_DIR}/${EXPERIMENT_NAME}_$(date +%Y%m%d_%H%M%S).log}
echo "[train_janus_nli] log file: ${LOG_FILE}"

# -----------------------------
# Batch divisibility sanity check (matches the full grpo script logic)
# -----------------------------
gcd() {
  local a=$1
  local b=$2
  local t
  while [ "$b" -ne 0 ]; do
    t=$((a % b))
    a=$b
    b=$t
  done
  echo "$a"
}

if [ "${PREDICT_ROLL_N}" -le 0 ] || [ "${JUDGE_ROLL_N}" -le 0 ]; then
  echo "[ERROR] PREDICT_ROLL_N and JUDGE_ROLL_N must both be positive integers." >&2
  exit 1
fi

GROUP_GCD=$(gcd "${PREDICT_ROLL_N}" "${JUDGE_ROLL_N}")
BATCH_DIVISOR_STEP=$((JUDGE_ROLL_N / GROUP_GCD))
if [ $((ROLLOUT_BATCH_SIZE_VALUE % BATCH_DIVISOR_STEP)) -ne 0 ]; then
  echo "[ERROR] ROLLOUT_BATCH_SIZE (${ROLLOUT_BATCH_SIZE_VALUE}) must be divisible by ${BATCH_DIVISOR_STEP}." >&2
  exit 1
fi
DEFAULT_ACTOR_GLOBAL_BATCH_SIZE=$((ROLLOUT_BATCH_SIZE_VALUE / BATCH_DIVISOR_STEP))
ACTOR_GLOBAL_BATCH_SIZE=${ACTOR_GLOBAL_BATCH_SIZE:-${DEFAULT_ACTOR_GLOBAL_BATCH_SIZE}}
if [ $((ROLLOUT_BATCH_SIZE_VALUE % ACTOR_GLOBAL_BATCH_SIZE)) -ne 0 ]; then
  echo "[ERROR] ACTOR_GLOBAL_BATCH_SIZE (${ACTOR_GLOBAL_BATCH_SIZE}) must divide ROLLOUT_BATCH_SIZE (${ROLLOUT_BATCH_SIZE_VALUE})." >&2
  exit 1
fi
MERGED_GROUP_FACTOR=$((PREDICT_ROLL_N + JUDGE_ROLL_N))
if [ $(( ((ROLLOUT_BATCH_SIZE_VALUE / ACTOR_GLOBAL_BATCH_SIZE) * MERGED_GROUP_FACTOR) % JUDGE_ROLL_N )) -ne 0 ]; then
  echo "[ERROR] Current batch-size settings are incompatible with merged predict/judge updates." >&2
  exit 1
fi

# -----------------------------
# Auxiliary text reward backend sanity check.
# -----------------------------
echo "[train_janus_nli] predictor text reward backend: ${PREDICT_TEXT_REWARD_TYPE}"
if [ "${PREDICT_TEXT_REWARD_TYPE}" = "embedding" ]; then
  echo "[train_janus_nli] pinging embedding service ${VLLM_EMBEDDING_BASE_URL} ..."
  EMBED_PING_BODY=$(printf '{"model":"%s","input":["healthcheck"]}' "${VLLM_EMBEDDING_MODEL}")
  EMBED_PING_CODE=$(curl -sS --max-time 15 --noproxy '*' \
    -o /tmp/janus_embed_ping.$$ -w "%{http_code}" \
    -X POST "${VLLM_EMBEDDING_BASE_URL}/embeddings" \
    -H "Content-Type: application/json" \
    -H "Authorization: Bearer ${VLLM_EMBEDDING_API_KEY}" \
    -d "${EMBED_PING_BODY}" || echo "000")
  if [ "${EMBED_PING_CODE}" != "200" ]; then
    echo "[ERROR] embedding service health check FAILED (HTTP ${EMBED_PING_CODE})." >&2
    echo "        URL:   ${VLLM_EMBEDDING_BASE_URL}" >&2
    echo "        MODEL: ${VLLM_EMBEDDING_MODEL}" >&2
    echo "        body:" >&2
    sed 's/^/          /' /tmp/janus_embed_ping.$$ >&2 || true
    rm -f /tmp/janus_embed_ping.$$
    echo "        Fix the endpoint or set PREDICT_TEXT_REWARD_TYPE=none|bleu|nli." >&2
    exit 1
  fi
  rm -f /tmp/janus_embed_ping.$$
  echo "[train_janus_nli] embedding service OK."
elif [ "${PREDICT_TEXT_REWARD_TYPE}" = "nli" ]; then
  if [ -z "${PREDICT_NLI_MODEL_PATH}" ]; then
    echo "[ERROR] PREDICT_TEXT_REWARD_TYPE=nli but PREDICT_NLI_MODEL_PATH is empty." >&2
    exit 1
  fi
  if [ ! -d "${PREDICT_NLI_MODEL_PATH}" ]; then
    echo "[ERROR] Local NLI model directory not found: ${PREDICT_NLI_MODEL_PATH}" >&2
    exit 1
  fi
  if [ ! -f "${PREDICT_NLI_MODEL_PATH}/config.json" ]; then
    echo "[ERROR] ${PREDICT_NLI_MODEL_PATH}/config.json not found. Please copy a full HF model snapshot." >&2
    exit 1
  fi
  if [ ! -d "${PREDICT_NLI_TOKENIZER_PATH}" ]; then
    echo "[ERROR] Local NLI tokenizer directory not found: ${PREDICT_NLI_TOKENIZER_PATH}" >&2
    exit 1
  fi
  if [ ! -f "${PREDICT_NLI_TOKENIZER_PATH}/tokenizer.json" ] \
    && [ ! -f "${PREDICT_NLI_TOKENIZER_PATH}/vocab.txt" ] \
    && [ ! -f "${PREDICT_NLI_TOKENIZER_PATH}/spiece.model" ] \
    && [ ! -f "${PREDICT_NLI_TOKENIZER_PATH}/sentencepiece.bpe.model" ]; then
    echo "[ERROR] ${PREDICT_NLI_TOKENIZER_PATH} does not look like a complete HF tokenizer snapshot." >&2
    exit 1
  fi
  echo "[train_janus_nli] local NLI model/tokenizer paths OK: ${PREDICT_NLI_MODEL_PATH} / ${PREDICT_NLI_TOKENIZER_PATH}"
